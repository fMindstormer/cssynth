#!/usr/bin/env python3
"""Compare compiler methods on a target set at a fixed rendered fidelity.

    python bench/evaluate.py --set heldout --method full
    python bench/evaluate.py --set dev --method fast --out bench/eval/dev-fast.json
    python bench/evaluate.py --set heldout --compare base full     # saved runs, side by side

Sets: "dev" (the 66 targets the compiler was developed on, bench/cases.json)
and "heldout" (bench/heldout/, generated by families.py and not used while
developing). Every output is rendered in Chromium (render.js) and compared
with the target; an output counts as solved at >= 99% pixel match. The
summary gives, per family, how many were solved, their total length, and
the CPU time spent compiling (process time, so parallel runs don't inflate
it). Methods are compared on the targets all of them solve.
"""

import argparse
import json
import os
import subprocess
import sys
import time
from collections import defaultdict
from multiprocessing import Pool
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "bench"))
from cssynth import compiler, search, simplify  # noqa: E402

BENCH = ROOT / "bench"
FIDELITY = 99.0


def _full(path):
    return compiler.compile_image(path)


def _fast(path):
    return compiler.compile_image(path, research=False)


def _base(path):
    """The compiler as of v0.5.0: none of the switches below."""
    search.MOTIFS, search.SCALE_MOVES, simplify.PLAINER = set(), False, False
    search.SAME_COLOR = -1
    return compiler.compile_image(path)


def _base_more(path):
    """base climbing 14 starts per step instead of 10: about the CPU time
    of the default compiler, for comparisons at equal compute."""
    search.MOTIFS, search.SCALE_MOVES, simplify.PLAINER = set(), False, False
    search.SAME_COLOR, search.TOP_STARTS = -1, 14
    return compiler.compile_image(path)


def _full_more(n):
    """The default compiler climbing n starts per step instead of 10."""
    def run(path):
        search.TOP_STARTS = n
        return compiler.compile_image(path)
    return run


def _fixes(path):
    """Everything but motifs."""
    search.MOTIFS = set()
    return compiler.compile_image(path)


def _motifs(kinds, same_color=search.SAME_COLOR):
    def run(path):
        search.MOTIFS, search.SAME_COLOR = set(kinds), same_color
        return compiler.compile_image(path)
    return run


def _learned(path):
    """Nest and symmetric motifs, accepted by the filter trained in
    proposals.py (its model file in $PROPOSAL_MODEL) instead of by the step
    rule."""
    import proposals
    global _policy
    if _policy is None:
        _policy = proposals.learned_policy(os.environ["PROPOSAL_MODEL"])
    search.MOTIFS, search.MOTIF_POLICY = {"nest", "symmetric"}, _policy
    return compiler.compile_image(path)


_policy = None

# name: path -> (code, info, model)
METHODS = {"full": _full, "fast": _fast, "base": _base, "base-more": _base_more,
           **{f"full-{n}": _full_more(n) for n in (16, 20)}, "fixes": _fixes,
           "nest": _motifs(["nest"]), "nest-sym": _motifs(["nest", "symmetric"]),
           "all-motifs": _motifs(["nest", "symmetric", "seeded"]),
           "nest-allcolors": _motifs(["nest"], same_color=-1), "learned": _learned}


def targets(name):
    """[(id, family, png path, reference length)]."""
    if name == "dev":
        cases = json.loads((BENCH / "cases.json").read_text())
        return [(c["id"], "dev", BENCH / "human" / f"{c['id']}.png", c["human_min_len"]) for c in cases]
    d = BENCH / name
    cases = json.loads((d / "cases.json").read_text())
    missing = [c for c in cases if not (d / f"{c['id']}.png").exists()]
    if missing:                     # targets are rendered where they are scored
        jobs = [{"html": (d / f"{c['id']}.html").read_text(), "out": str(d / f"{c['id']}.png")} for c in missing]
        (d / "jobs.json").write_text(json.dumps(jobs))
        subprocess.run(["node", str(BENCH / "render.js"), str(d / "jobs.json")], check=True, cwd=BENCH)
        (d / "jobs.json").unlink()
    return [(c["id"], c["family"], d / f"{c['id']}.png", c["ref_len"]) for c in cases]


def match(a, b, tol=8):
    return float((np.abs(a.astype(int) - b.astype(int)).max(2) <= tol).mean() * 100)


def work(args):
    method, (cid, fam, path, ref) = args
    t = time.process_time()
    code, info, _ = METHODS[method](path)
    return {"id": cid, "family": fam, "chars": len(code), "code": code, "ref_len": ref,
            "cpu": round(time.process_time() - t, 2), "variant": info.get("variant")}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", default="heldout")
    ap.add_argument("--method", default="full", choices=sorted(METHODS))
    ap.add_argument("--jobs", type=int, default=4)       # few enough to stay on fast cores
    ap.add_argument("--only")
    ap.add_argument("--out")
    ap.add_argument("--compare", nargs="+", metavar="METHOD",
                    help="only print saved runs of these methods on --set side by side")
    args = ap.parse_args()
    if args.compare:
        summarize({m: json.loads((BENCH / "eval" / f"{args.set}-{m}.json").read_text()) for m in args.compare})
        return
    tg = targets(args.set)
    if args.only:
        keep = set(args.only.split(","))
        tg = [t for t in tg if t[0] in keep]
    with Pool(args.jobs) as p:
        res = p.map(work, [(args.method, t) for t in tg], chunksize=1)

    out = Path(args.out or BENCH / "eval" / f"{args.set}-{args.method}.json")
    out_dir = BENCH / "eval" / f"{args.set}-{args.method}"
    out_dir.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(res, indent=1))       # kept if rendering fails
    jobs = [{"html": r["code"], "out": str(out_dir / f"{r['id']}.png")} for r in res]
    (out_dir / "jobs.json").write_text(json.dumps(jobs))
    subprocess.run(["node", str(BENCH / "render.js"), str(out_dir / "jobs.json")], check=True, cwd=BENCH)
    paths = {t[0]: t[2] for t in tg}
    for r in res:
        tgt = np.asarray(Image.open(paths[r["id"]]).convert("RGB"))
        got = np.asarray(Image.open(out_dir / f"{r['id']}.png").convert("RGB"))
        r["match"] = round(match(got, tgt), 2)
    out.write_text(json.dumps(res, indent=1))
    summarize({args.method: res})


def summarize(runs):
    """runs: {method: results}. Per family: solved, and on the targets every
    method solves, total characters and CPU seconds."""
    methods = list(runs)
    by = {m: {r["id"]: r for r in rs} for m, rs in runs.items()}
    ids = list(by[methods[0]])
    fams = defaultdict(list)
    for i in ids:
        fams[by[methods[0]][i]["family"]].append(i)
    print(f"{'family':10s}" + "".join(f"  {m:>28s}" for m in methods) + "   reference")
    for fam, members in list(fams.items()) + [("all", ids)]:
        common = [i for i in members if all(by[m][i]["match"] >= FIDELITY for m in methods)]
        cells = []
        for m in methods:
            solved = sum(by[m][i]["match"] >= FIDELITY for i in members)
            chars = sum(by[m][i]["chars"] for i in common)
            cpu = sum(by[m][i]["cpu"] for i in members)
            cells.append(f"{solved:2d}/{len(members):2d} {chars:6d} ch {cpu:7.0f} s")
        ref = sum(by[methods[0]][i]["ref_len"] for i in common)
        print(f"{fam:10s}" + "".join(f"  {c:>28s}" for c in cells) + f"   {ref:6d}")


if __name__ == "__main__":
    main()
